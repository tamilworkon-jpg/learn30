import { mkdirSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import Ajv from 'ajv/dist/2020';
import addFormats from 'ajv-formats';
import standaloneCode from 'ajv/dist/standalone';
import progressSchema from '../src/schemas/progress-schema.json';

const ajv = new Ajv({ allErrors: true, strict: false, code: { source: true, esm: true } });
addFormats(ajv);
const raw = standaloneCode(ajv, ajv.compile(progressSchema));
// Ajv emits CommonJS require() for runtime helpers; rewrite to ESM default imports for the browser.
const mods = [...new Set([...raw.matchAll(/require\("([^"]+)"\)/g)].map((m) => m[1]))];
const imports = mods.map((m, i) => `import __m${i} from ${JSON.stringify(m)};`).join('\n');
const code = imports + '\n' + mods.reduce((c, m, i) => c.split(`require(${JSON.stringify(m)})`).join(`__m${i}`), raw);
const out = join(resolve(import.meta.dirname, '..'), 'src', 'schemas', 'generated');
mkdirSync(out, { recursive: true });
writeFileSync(join(out, 'validate-progress.js'), `// Generated by scripts/build-validators.ts — do not edit.\n${code}`);
writeFileSync(
  join(out, 'validate-progress.d.ts'),
  "import type { ErrorObject } from 'ajv';\ndeclare const validate: ((data: unknown) => boolean) & { errors?: ErrorObject[] | null };\nexport default validate;\n",
);
console.log('Generated src/schemas/generated/validate-progress.js');
